#!/usr/bin/env python3
"""Check real original MAME BE0D collision translation before/after states.

The user-owned 1991 arcade game runs unmodified; debugger breakpoints
at BE0D and BE65 are READ-ONLY. Input CSV is PRIVATE, generated by
mame_capture_collision_be0d.lua. Public report emits counts, branch types
and a hash only: never original game RAM words, ROM, art or trackmaps.

The verified operation replaces two shared position/geometry references,
adds their two wrapped 16-bit deltas to four words for each axis, then
branches to the original collision retry at BCA5.
This does not establish the original force, impact type or car handling.
"""
from __future__ import annotations

import argparse
from collections import Counter
import csv
from hashlib import sha256
import json
from pathlib import Path

FIELDS=("frame","phase","ix","target_x","target_y","base_x","base_y",
        "x1","x2","x3","x4","y1","y2","y3","y4")
CAR_IX=tuple(0xE080+0x100*i for i in range(5))
X_KEYS=("x1","x2","x3","x4")
Y_KEYS=("y1","y2","y3","y4")


def _parse(row:dict[str,str])->dict:
    if not set(FIELDS).issubset(row):
        raise ValueError("Original MAME collision snapshot has missing columns")
    try:
        data={"frame":int(row["frame"]),"phase":row["phase"]}
        data.update((key,int(row[key],16)) for key in FIELDS[2:])
    except (TypeError,ValueError) as err:
        raise ValueError("Invalid original Z80 collision snapshot field") from err
    if (data["frame"]<=0 or data["phase"] not in ("ENTRY","EXIT")
            or data["ix"] not in CAR_IX
            or any(not 0<=data[key]<65536 for key in FIELDS[3:])):
        raise ValueError("Original CPU frame, car or 16-bit word outside verified domain")
    return data


def audit_rows(rows:list[dict[str,str]])->dict:
    if not rows or len(rows)%2:
        raise ValueError("Original live translation requires complete ENTRY/EXIT pairs")
    outcomes=Counter()
    cars=Counter()
    first=last=-1
    for i in range(0,len(rows),2):
        before,after=_parse(rows[i]),_parse(rows[i+1])
        if (before["phase"],after["phase"])!=("ENTRY","EXIT"):
            raise ValueError(f"Original BE0D/BE65 instruction order differs at pair {i//2}")
        if (before["frame"]!=after["frame"] or before["ix"]!=after["ix"]
                or (last!=-1 and before["frame"]<last)):
            raise ValueError("Original collision pair spans another frame or car")
        if any(before[k]!=after[k] for k in ("target_x","target_y")):
            raise ValueError("Original target words mutated inside BE0D routine")
        delta_x=(before["target_x"]-before["base_x"])&65535
        delta_y=(before["target_y"]-before["base_y"])&65535
        if after["base_x"]!=before["target_x"] or after["base_y"]!=before["target_y"]:
            raise ValueError("Original reference word replacement mismatch")
        for key in X_KEYS:
            if after[key]!=(before[key]+delta_x)&65535:
                raise ValueError(f"Original X geometry translation mismatch at {key}")
        for key in Y_KEYS:
            if after[key]!=(before[key]+delta_y)&65535:
                raise ValueError(f"Original Y geometry translation mismatch at {key}")
        kind=("both" if delta_x and delta_y else
              "x_only" if delta_x else "y_only" if delta_y else "neither")
        outcomes[kind]+=1
        cars[f"{before['ix']:04X}"]+=1
        if first<0:first=before["frame"]
        last=after["frame"]
    return {
        "source":"authentic original 1991 Indy Heat arcade MAME Z80 BE0D/BE65 read-only debugger",
        "original_translation_events":len(rows)//2,
        "original_debugger_snapshots":len(rows),
        "first_frame":first,"last_frame":last,
        "branch_counts":dict(sorted(outcomes.items())),
        "events_by_car":dict(sorted(cars.items())),
        "original_translation_words_per_axis":4,
        "original_position_geometry_mismatches":0,
        "scope":"Live bounded collision translation; external impact force, terrain and retry remain separate"
    }


def audit_file(path:Path)->dict:
    with path.open(newline="",encoding="utf-8") as f:
        reader=csv.DictReader(f)
        if not set(FIELDS).issubset(reader.fieldnames or ()):
            raise ValueError("Original private collision trace CSV header incorrect")
        report=audit_rows(list(reader))
    digest=sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda:f.read(1<<20),b""):
            digest.update(chunk)
    report["private_trace_sha256"]=digest.hexdigest()
    return report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("private_be0d_trace",type=Path)
    parser.add_argument("--out",type=Path,
                        default=Path("local/private-runtime/be0d_live_audit.json"))
    args=parser.parse_args()
    report=audit_file(args.private_be0d_trace)
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,indent=2))


if __name__=="__main__":main()
