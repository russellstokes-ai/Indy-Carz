#!/usr/bin/env python3
"""Audit a controlled MAME collision fallback after one explicit E92E injection.

Original program: Indy Heat arcade rev 1, original master Z80, MAME 0.264.
Input is a PRIVATE CSV generated by tools/mame_probe_bc8c_forced_fallback.lua.

Unlike a normal-play trace, this is a CONTROLLED experiment: one breakpoint
sets E92E to 0x11 at original BCA5 so the original INC reaches threshold
0x12. Strictly validate the thirty ordered original CPU writes and require
the probe to have checked every byte against the actual source/expected
reset value. The CSV contains no proprietary ROM, memory or graphic bytes.
"""
from __future__ import annotations
import argparse
import csv
from hashlib import sha256
import json
from pathlib import Path

FIELDS = ("frame","kind","pc","ix","addr","correct","counter")
ORIGINAL_IX = 0xE080
RETRY_THRESHOLD = 18
BACKUP_WORDS = (
    (0xBCB8,0xE72B), (0xBCBE,0xE735), (0xBCC4,0xE72D),
    (0xBCCA,0xE72F), (0xBCD0,0xE731), (0xBCD6,0xE733),
    (0xBCDC,0xE737), (0xBCE2,0xE739), (0xBCE8,0xE73B),
    (0xBCEE,0xE73D), (0xBCF4,0xE767)
)
EXPECTED = (
    (("car_reset",0xC468,0xE0C1),
     ("global_reset",0xC46F,0xE76A),
     ("global_reset",0xC475,0xE76B),
     ("global_reset",0xC475,0xE76C),
     ("global_reset",0xC47B,0xE765),
     ("global_reset",0xC47B,0xE766),
     ("car_reset",0xC47E,0xE0CD),
     ("car_reset",0xC482,0xE0CC))
    + tuple(("restore",pc,address+part)
            for pc,address in BACKUP_WORDS for part in (0,1))
)


def audit_rows(rows: list[dict[str,str]]) -> dict:
    if len(rows) != len(EXPECTED):
        raise ValueError(f"One complete fallback requires exactly {len(EXPECTED)} writes")
    frame_number = None
    car = None
    for i,(row,expected) in enumerate(zip(rows,EXPECTED)):
        if not set(FIELDS).issubset(row):
            raise ValueError("Original controlled fallback CSV missing columns")
        try:
            frame = int(row["frame"])
            pc = int(row["pc"],16)
            ix = int(row["ix"],16)
            address = int(row["addr"],16)
            correct = int(row["correct"])
            counter = int(row["counter"])
        except (TypeError, ValueError) as err:
            raise ValueError(f"Invalid controlled fallback row {i}") from err
        if frame_number is None:frame_number=frame
        if car is None:car=ix
        if frame<=0 or frame!=frame_number or ix!=car or ix!=ORIGINAL_IX:
            raise ValueError(f"Unexpected original collision frame/car sequence at write {i}")
        if (row["kind"],pc,address)!=expected:
            raise ValueError(f"Wrong original C468/rollback PC or destination at write {i}")
        if counter!=RETRY_THRESHOLD:
            raise ValueError(f"Original collision fallback counter not 18 at write {i}")
        if correct!=1:
            raise ValueError(f"Original rollback source/reset mismatch at write {i}")
    return {
        "source":"controlled real MAME 0.264 Indy Heat rev1 Z80 breakpoint/write-tap",
        "source_kind":"controlled RAM injection; NOT natural racing",
        "original_retry_counter":RETRY_THRESHOLD,
        "original_cpu_write_events":len(EXPECTED),
        "original_car_byte_resets":3,
        "original_global_reset_bytes":5,
        "original_restored_16bit_words":len(BACKUP_WORDS),
        "original_restored_bytes":2*len(BACKUP_WORDS),
        "original_source_byte_mismatches":0,
        "original_car_ix":f"{ORIGINAL_IX:04X}",
        "frame":frame_number,
        "limitations":"BCFA full collision forces, natural 18-retry probability and track impact physics remain unknown"
    }


def audit_file(path:Path) -> dict:
    with path.open(newline="",encoding="utf-8") as f:
        reader=csv.DictReader(f)
        if not set(FIELDS).issubset(reader.fieldnames or ()):
            raise ValueError("Original controlled fallback trace header mismatch")
        report=audit_rows(list(reader))
    h=sha256()
    with path.open("rb") as f:
        for piece in iter(lambda:f.read(1<<20),b""):h.update(piece)
    report["private_capture_sha256"]=h.hexdigest()
    return report


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("private_controlled_capture",type=Path)
    parser.add_argument("--out",type=Path,
                        default=Path("local/private-runtime/controlled_bc8c_audit.json"))
    args=parser.parse_args()
    report=audit_file(args.private_controlled_capture)
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,indent=2))
