#!/usr/bin/env python3
"""Summarise original Indy Heat arcade per-frame RAM changes by car state field.

Analyses PRIVATE captures generated by mame_capture_carstate.lua.
No ROMs or actual RAM values are written to output: only change frequencies,
which are evidence for isolating original state variables. Does not label any
unknown byte as speed, fuel, AI, damage or car position without tracing.
"""
from __future__ import annotations
import argparse
import collections
import json
from pathlib import Path

MAGIC = b"ICR1"
RAM_BASE = 0xE000
RECORD_BYTES = 0x0A00
SLOTS = [0xE080 + i * 0x100 for i in range(6)]  # Five racers + extra record


def analyse_bytes(data: bytes) -> dict:
    if len(data) < 12 or data[:4] != MAGIC:
        raise ValueError("Not an Indy Carz ICR1 original RAM capture")
    base = int.from_bytes(data[4:8], "little")
    length = int.from_bytes(data[8:12], "little")
    if base != RAM_BASE or length != RECORD_BYTES:
        raise ValueError("Unexpected original master RAM region dimensions")
    payload = data[12:]
    stride = RECORD_BYTES + 4
    if not payload or len(payload) % stride:
        raise ValueError("Truncated or empty original arcade RAM frames")
    count = len(payload) // stride
    slot_changes = {f"E{n:03X}": [0] * 256 for n in SLOTS}
    total_transitions = [0] * RECORD_BYTES
    first_frame = previous_frame = None
    last_frame_num = -1
    for index in range(count):
        frame_start = index * stride
        frame_no = int.from_bytes(payload[frame_start:frame_start + 4], "little")
        if frame_no <= last_frame_num:
            raise ValueError("Frame numbers are not strictly increasing")
        last_frame_num = frame_no
        ram = payload[frame_start + 4:frame_start + stride]
        if previous_frame is None:
            first_frame = frame_no
            previous_frame = ram
            continue
        for offset, (prev, current) in enumerate(zip(previous_frame, ram)):
            if prev != current:
                total_transitions[offset] += 1
        for baseaddr in SLOTS:
            key = f"E{baseaddr - 0xE000:03X}"
            start = baseaddr - RAM_BASE
            fields = slot_changes[key]
            for offset in range(256):
                fields[offset] += previous_frame[start + offset] != ram[start + offset]
        previous_frame = ram
    summary = {}
    for base, fields in slot_changes.items():
        summary[base] = {
            "changed_field_count": sum(n > 0 for n in fields),
            "total_byte_transitions": sum(fields),
            "fields": [
                {"offset_hex": f"{offset:02X}", "changed_frames": changes}
                for offset, changes in enumerate(fields) if changes
            ],
        }
    top = sorted(enumerate(total_transitions), key=lambda t: (-t[1], t[0]))[:100]
    return {
        "source": "original 1991 arcade MAME per-frame master RAM capture",
        "frames": count,
        "frame_numbers": {"first": first_frame, "last": last_frame_num},
        "observation_transitions": count - 1,
        "car_related_records": summary,
        "most_dynamic_ram_addresses": [
            {"address": f"{RAM_BASE + offset:04X}", "changed_frames": changes}
            for offset, changes in top if changes
        ],
        "scope": "change-frequency candidates only; exact game-state meanings require instruction tracing",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("capture", type=Path, help="Private master_ram_frames.bin")
    parser.add_argument("--out", type=Path,
                        default=Path("local/engine-extraction/runtime/ram_diff_summary.json"))
    args = parser.parse_args()
    report = analyse_bytes(args.capture.read_bytes())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("Analysed", report["frames"], "original arcade RAM frames")
    print("Summary:", args.out)
    print("Game field semantics are NOT automatically verified.")


if __name__ == "__main__":
    main()
